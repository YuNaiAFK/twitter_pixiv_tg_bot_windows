def translate_tag(value: str) -> str:
    """
    Return the Traditional Chinese name for a tag value.

    Unknown tags are returned unchanged rather than dropped: a reader
    is better served by the original English than by a missing tag.
    """
    if not value:
        return value
    return TAG_TRANSLATIONS.get(value.strip().lower(), value)
